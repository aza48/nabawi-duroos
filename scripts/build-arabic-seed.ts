/**
 * Builds src/server/seed/content/arabic.ts from the Arabic translations in docs/research/translations:
 *   <slug>.ar.html  a guide: a header comment with title_ar and summary_ar, then the Arabic body HTML;
 *   faqs-*.ar.json  answers: { "<slug>": { "questionAr": "...", "answerHtmlAr": "..." } }.
 * The content sync (src/server/seed/content/sync.ts) attaches them to the seeded guides and answers by slug.
 * Run after editing a translation: npx tsx --tsconfig tsconfig.json scripts/build-arabic-seed.ts
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = join(process.cwd(), "docs/research/translations");
const OUT = join(process.cwd(), "src/server/seed/content/arabic.ts");

type ArGuide = { titleAr: string; summaryAr: string; bodyHtmlAr: string };
type ArFaq = { questionAr: string; answerHtmlAr: string };

const guides: Record<string, ArGuide> = {};
const faqs: Record<string, ArFaq> = {};

for (const file of readdirSync(DIR).sort()) {
  if (file.endsWith(".ar.html")) {
    const raw = readFileSync(join(DIR, file), "utf8");
    const head = /^\s*<!--([\s\S]*?)-->/.exec(raw);
    if (!head) throw new Error(`${file}: no header comment`);
    const field = (k: string) => new RegExp(`^\\s*${k}:\\s*(.+)$`, "m").exec(head[1])?.[1].trim();
    const slug = field("slug");
    const titleAr = field("title_ar");
    const summaryAr = field("summary_ar");
    if (!slug || !titleAr || !summaryAr) throw new Error(`${file}: header needs slug, title_ar and summary_ar`);
    if (`${slug}.ar.html` !== file) throw new Error(`${file}: slug in the header is ${slug}`);
    guides[slug] = { titleAr, summaryAr, bodyHtmlAr: raw.slice(head.index + head[0].length).trim() };
  } else if (/^faqs-.*\.ar\.json$/.test(file)) {
    const data = JSON.parse(readFileSync(join(DIR, file), "utf8")) as Record<string, ArFaq>;
    for (const [slug, v] of Object.entries(data)) {
      if (!v.questionAr?.trim() || !v.answerHtmlAr?.trim()) throw new Error(`${file}: ${slug} is missing a field`);
      if (faqs[slug]) throw new Error(`${file}: ${slug} is translated twice`);
      faqs[slug] = { questionAr: v.questionAr.trim(), answerHtmlAr: v.answerHtmlAr.trim() };
    }
  }
}

writeFileSync(
  OUT,
  `/* eslint-disable */
// Generated by scripts/build-arabic-seed.ts from docs/research/translations. Do not edit by hand: edit the
// translation file and run the script again.

export type ArabicGuide = { titleAr: string; summaryAr: string; bodyHtmlAr: string };
export type ArabicFaq = { questionAr: string; answerHtmlAr: string };

export const ARABIC_GUIDES: Record<string, ArabicGuide> = ${JSON.stringify(guides, null, 1)};

export const ARABIC_FAQS: Record<string, ArabicFaq> = ${JSON.stringify(faqs, null, 1)};
`,
);
console.log(`Arabic: ${Object.keys(guides).length} guides, ${Object.keys(faqs).length} answers -> ${OUT}`);
